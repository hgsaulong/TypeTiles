-- Initial ONLINE schema, based on server/src/db.ts on 2026-10-18.
-- Run the whole file in the Supabase SQL Editor as the postgres role.
-- Creates empty application tables; does not copy SQLite data or use auth.users.
-- Backend PostgreSQL support is still required before deploying Type Tiles.
-- Browser access is intentionally denied: Type Tiles uses its own API/JWT auth.
BEGIN;

SELECT pg_advisory_xact_lock(548911, 1);

CREATE TABLE IF NOT EXISTS public.typetiles_schema_migrations (
  version TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE public.typetiles_schema_migrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.typetiles_schema_migrations FROM PUBLIC, anon, authenticated;

DO $migration$
DECLARE
  table_name TEXT;
  sequence_name TEXT;
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.typetiles_schema_migrations
    WHERE version = '20261018000100'
  ) THEN
    RAISE NOTICE 'Type Tiles initial migration is already applied; no changes made.';
    RETURN;
  END IF;

  -- Refuse to silently accept conflicting existing tables or modify their data.
  FOREACH table_name IN ARRAY ARRAY[
    'users', 'email_verification_codes', 'email_verification_rate_limits',
    'password_reset_codes', 'password_reset_rate_limits', 'user_stats',
    'matches', 'match_participants', 'match_results', 'admin_logs', 'feedback'
  ] LOOP
    IF to_regclass(format('public.%I', table_name)) IS NOT NULL THEN
      RAISE EXCEPTION 'public.% already exists. Stop and review the existing schema; no application changes applied.', table_name;
    END IF;
  END LOOP;

  CREATE TABLE public.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    display_name TEXT NOT NULL,
    avatar TEXT,
    tier TEXT DEFAULT 'Volt',
    role TEXT DEFAULT 'player',
    is_banned INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    background TEXT,
    session_version INTEGER NOT NULL DEFAULT 0,
    email_verified INTEGER NOT NULL DEFAULT 0,
    -- Existing authentication uses epoch milliseconds, beyond INTEGER range.
    email_verified_at BIGINT
  );

  CREATE TABLE public.email_verification_codes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    code_hash TEXT NOT NULL,
    expires_at BIGINT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    consumed_at BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
  );
  CREATE INDEX email_verification_user_created
    ON public.email_verification_codes(user_id, created_at);

  CREATE TABLE public.email_verification_rate_limits (
    key TEXT PRIMARY KEY,
    window_start BIGINT NOT NULL,
    count INTEGER NOT NULL,
    last_request BIGINT NOT NULL
  );

  CREATE TABLE public.password_reset_codes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    code_hash TEXT NOT NULL,
    expires_at BIGINT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    consumed_at BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
  );
  CREATE INDEX password_reset_user_created
    ON public.password_reset_codes(user_id, created_at);

  CREATE TABLE public.password_reset_rate_limits (
    key TEXT PRIMARY KEY,
    window_start BIGINT NOT NULL,
    count INTEGER NOT NULL,
    last_request BIGINT NOT NULL
  );

  CREATE TABLE public.user_stats (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
    games_played INTEGER DEFAULT 0,
    wins INTEGER DEFAULT 0,
    losses INTEGER DEFAULT 0,
    total_score INTEGER DEFAULT 0,
    -- SQLite accepts fractional WPM despite its original INTEGER declaration.
    best_wpm DOUBLE PRECISION DEFAULT 0,
    avg_accuracy DOUBLE PRECISION DEFAULT 0.0,
    top_combo INTEGER DEFAULT 0,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE public.matches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode TEXT NOT NULL,
    difficulty TEXT NOT NULL,
    round_time INTEGER DEFAULT 90,
    word_set TEXT NOT NULL,
    status TEXT DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMPTZ,
    practice_format TEXT NOT NULL DEFAULT 'word-phrase',
    background TEXT DEFAULT 'blues'
  );

  CREATE TABLE public.match_participants (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    score INTEGER DEFAULT 0,
    wpm DOUBLE PRECISION DEFAULT 0,
    accuracy DOUBLE PRECISION DEFAULT 0.0,
    position INTEGER,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    completed_words INTEGER DEFAULT 0,
    error_rate DOUBLE PRECISION DEFAULT 0.0,
    end_reason TEXT,
    remaining_lives INTEGER DEFAULT 0
  );

  CREATE TABLE public.match_results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    result TEXT NOT NULL,
    rank_change INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE public.admin_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id INTEGER NOT NULL REFERENCES public.users(id),
    action TEXT NOT NULL,
    target_user_id INTEGER REFERENCES public.users(id),
    details TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE public.feedback (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  FOREACH table_name IN ARRAY ARRAY[
    'users', 'email_verification_codes', 'email_verification_rate_limits',
    'password_reset_codes', 'password_reset_rate_limits', 'user_stats',
    'matches', 'match_participants', 'match_results', 'admin_logs', 'feedback'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated', table_name);
  END LOOP;

  -- Only these nine tables have an id identity. Never look up an id on
  -- email_verification_rate_limits or password_reset_rate_limits (key is PK).
  FOREACH table_name IN ARRAY ARRAY[
    'users', 'email_verification_codes', 'password_reset_codes', 'user_stats',
    'matches', 'match_participants', 'match_results', 'admin_logs', 'feedback'
  ] LOOP
    sequence_name := pg_get_serial_sequence(format('public.%I', table_name), 'id');
    IF sequence_name IS NOT NULL THEN
      EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', sequence_name);
    END IF;
  END LOOP;

  INSERT INTO public.typetiles_schema_migrations(version) VALUES ('20261018000100');
END
$migration$;

COMMIT;

-- Expected: the 11 application tables and one migration tracking table, RLS true.
SELECT tablename, rowsecurity
FROM pg_tables
WHERE schemaname = 'public'
  AND tablename IN (
    'typetiles_schema_migrations', 'users', 'email_verification_codes',
    'email_verification_rate_limits', 'password_reset_codes',
    'password_reset_rate_limits', 'user_stats', 'matches',
    'match_participants', 'match_results', 'admin_logs', 'feedback'
  )
ORDER BY tablename;
